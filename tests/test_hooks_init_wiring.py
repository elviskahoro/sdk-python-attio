"""Tests for the SDK lifecycle hooks ``init_hooks`` wiring.

``src/attio/_hooks/registration.py`` is a one-time-generated, maintainer-editable
scaffolding file (not tracked in ``.speakeasy/gen.lock``) whose header
instructs maintainers to register lifecycle hooks (``sdk_init``,
``before_request``, ``after_success``, ``after_error``) inside the
``init_hooks`` function. Commit ``dc8cebc`` (the 2026-03-28 regeneration)
overwrote ``src/attio/_hooks/sdkhooks.py`` — a "DO NOT EDIT" generated file —
with a clean Speakeasy template that lacked both the
``from .registration import init_hooks`` import and the ``init_hooks(self)``
call in ``SDKHooks.__init__``, orphaning ``init_hooks``: hooks a maintainer
added to ``registration.py`` were silently never registered. The same commit
also dropped the ``from .registration import *`` re-export from the hooks
package ``__init__.py``.

These tests pin the fix and the regeneration-safe patch in
``ci/post_generate_patch.py`` that re-injects the wiring after every
``speakeasy run`` so a future regeneration cannot strip it again.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import httpx
import pytest

from attio import SDK
from attio._hooks import sdkhooks as sdkhooks_mod
from attio._hooks.types import BeforeRequestHook

REPO_ROOT = Path(__file__).resolve().parent.parent
PATCH_SCRIPT = REPO_ROOT / "ci" / "post_generate_patch.py"
COMMITTED_SDKHOOKS = REPO_ROOT / "src" / "attio" / "_hooks" / "sdkhooks.py"
COMMITTED_HOOKS_INIT = REPO_ROOT / "src" / "attio" / "_hooks" / "__init__.py"
FIXTURE_SDKHOOKS_UNPATCHED = REPO_ROOT / "tests" / "fixtures" / "sdkhooks_unpatched.txt"
FIXTURE_HOOKS_INIT_UNPATCHED = REPO_ROOT / "tests" / "fixtures" / "hooks_init_unpatched.txt"


def _load_patch_module():
    spec = importlib.util.spec_from_file_location(
        "attio_test_post_generate_patch_hooks", PATCH_SCRIPT
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


PGP = _load_patch_module()

REGISTRATION_IMPORT = "from .registration import init_hooks"
REGISTRATION_REEXPORT = "from .registration import *"
INIT_HOOKS_CALL = "init_hooks(self)"
AFTER_ERROR_HOOKS_ANCHOR = "self.after_error_hooks: List[AfterErrorHook] = []"


def _unpatched_sdkhooks() -> str:
    """The post-regeneration snapshot, pinned as a fixture so surrounding
    structural drift in the generated template is caught (not just the two
    wiring lines)."""
    return FIXTURE_SDKHOOKS_UNPATCHED.read_text()


def _unpatched_hooks_init() -> str:
    return FIXTURE_HOOKS_INIT_UNPATCHED.read_text()


# ---------------------------------------------------------------------------
# Committed-file regression pins
# ---------------------------------------------------------------------------


def test_committed_sdkhooks_imports_init_hooks() -> None:
    assert REGISTRATION_IMPORT in COMMITTED_SDKHOOKS.read_text()


def test_committed_sdkhooks_calls_init_hooks_in_constructor() -> None:
    text = COMMITTED_SDKHOOKS.read_text()
    assert "def __init__(self) -> None:" in text
    assert INIT_HOOKS_CALL in text
    init_idx = text.index("def __init__(self) -> None:")
    call_idx = text.index(INIT_HOOKS_CALL)
    next_method_idx = text.index("def register_sdk_init_hook", call_idx)
    assert init_idx < call_idx < next_method_idx


def test_committed_hooks_init_reexports_registration() -> None:
    assert REGISTRATION_REEXPORT in COMMITTED_HOOKS_INIT.read_text()


# ---------------------------------------------------------------------------
# Post-generation patch: src/attio/_hooks/sdkhooks.py
# ---------------------------------------------------------------------------


def test_init_hooks_wiring_is_noop_on_committed_file(tmp_path: Path) -> None:
    target = tmp_path / "sdkhooks.py"
    target.write_text(COMMITTED_SDKHOOKS.read_text())

    assert PGP.ensure_init_hooks_wiring(target) is False
    assert target.read_text() == COMMITTED_SDKHOOKS.read_text()


def test_init_hooks_wiring_applies_to_unpatched_and_matches_committed(
    tmp_path: Path,
) -> None:
    target = tmp_path / "sdkhooks.py"
    target.write_text(_unpatched_sdkhooks())

    assert PGP.ensure_init_hooks_wiring(target) is True
    assert target.read_text() == COMMITTED_SDKHOOKS.read_text()


def test_init_hooks_wiring_is_idempotent_after_application(tmp_path: Path) -> None:
    target = tmp_path / "sdkhooks.py"
    target.write_text(_unpatched_sdkhooks())

    first_changed = PGP.ensure_init_hooks_wiring(target)
    first_text = target.read_text()

    second_changed = PGP.ensure_init_hooks_wiring(target)

    assert first_changed is True
    assert second_changed is False
    assert target.read_text() == first_text


def test_init_hooks_wiring_raises_when_types_import_missing(tmp_path: Path) -> None:
    target = tmp_path / "sdkhooks.py"
    target.write_text(
        '"""Code generated by Speakeasy (https://speakeasy.com). DO NOT EDIT."""\n\n'
        "import httpx\n\n\n"
        "class SDKHooks:\n"
        "    def __init__(self) -> None:\n"
        f"        {AFTER_ERROR_HOOKS_ANCHOR}\n"
    )

    with pytest.raises(RuntimeError, match=r"from \.types import \("):
        PGP.ensure_init_hooks_wiring(target)


def test_init_hooks_wiring_raises_when_call_anchor_missing(tmp_path: Path) -> None:
    """When the import is present but the __init__ anchor drifts, the patch
    must fail loudly rather than silently leaving init_hooks uncalled."""
    text = COMMITTED_SDKHOOKS.read_text().replace(
        AFTER_ERROR_HOOKS_ANCHOR,
        "self.after_error_hooks: list[AfterErrorHook] = []",  # altered layout
        1,
    )
    text = text.replace("        " + INIT_HOOKS_CALL + "\n", "", 1)
    target = tmp_path / "sdkhooks.py"
    target.write_text(text)

    with pytest.raises(RuntimeError, match="after_error_hooks"):
        PGP.ensure_init_hooks_wiring(target)


def test_init_hooks_wiring_output_compiles(tmp_path: Path) -> None:
    target = tmp_path / "sdkhooks.py"
    target.write_text(_unpatched_sdkhooks())

    PGP.ensure_init_hooks_wiring(target)

    compile(target.read_text(), str(target), "exec")


