# End-to-end: the SDK actually invokes init_hooks and runs registered hooks
# ---------------------------------------------------------------------------


def test_sdkhooks_constructor_calls_init_hooks(monkeypatch: pytest.MonkeyPatch) -> None:
    """The core regression: SDKHooks.__init__ must call init_hooks so a
    maintainer's registrations run."""
    received: list = []

    def spy_init_hooks(hooks):
        received.append(hooks)

    monkeypatch.setattr(sdkhooks_mod, "init_hooks", spy_init_hooks)

    from attio._hooks.sdkhooks import SDKHooks

    instance = SDKHooks()

    assert len(received) == 1
    assert received[0] is instance


def test_before_request_hook_registered_via_init_hooks_fires(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A before_request hook a maintainer adds via init_hooks must mutate the
    outgoing request during real SDK request processing. Faithful because a
    maintainer editing registration.py changes registration.init_hooks, which
    sdkhooks binds into its module namespace via ``from .registration import
    init_hooks``; patching that bound name is what SDKHooks.__init__ resolves
    at construction time."""
    captured: dict = {}

    class HeaderInjectionHook(BeforeRequestHook):
        def before_request(self, hook_ctx, request):
            request.headers["X-Custom-Header"] = "injected-by-hook"
            return request

    def maintainer_init_hooks(hooks):
        hooks.register_before_request_hook(HeaderInjectionHook())

    monkeypatch.setattr(sdkhooks_mod, "init_hooks", maintainer_init_hooks)

    def handler(request: httpx.Request) -> httpx.Response:
        captured["x-custom-header"] = request.headers.get("X-Custom-Header")
        captured["auth"] = request.headers.get("authorization")
        return httpx.Response(
            200,
            headers={"content-type": "application/json"},
            content=json.dumps({"active": False}).encode(),
            request=request,
        )

    with SDK(
        oauth2="test-token",
        client=httpx.Client(
            transport=httpx.MockTransport(handler), follow_redirects=True
        ),
    ) as sdk:
        result = sdk.meta.get_v2_self()

    assert captured["x-custom-header"] == "injected-by-hook"
    assert captured["auth"] is not None
    assert result is not None


# ---------------------------------------------------------------------------
# Subprocess: the patch script is a no-op on the committed tree
# ---------------------------------------------------------------------------


def test_patch_subprocess_is_noop_on_committed_hooks_files() -> None:
    before_sdkhooks = COMMITTED_SDKHOOKS.read_text()
    before_init = COMMITTED_HOOKS_INIT.read_text()

    result = subprocess.run(
        [sys.executable, str(PATCH_SCRIPT)],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
        check=False,
    )

    assert result.returncode == 0, result.stderr
    assert COMMITTED_SDKHOOKS.read_text() == before_sdkhooks
    assert COMMITTED_HOOKS_INIT.read_text() == before_init
